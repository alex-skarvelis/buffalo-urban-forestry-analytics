import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

def generate_regression_plot(csv_path="database_output.csv", output_path="species_size_vs_benefits_regression.png"):
    """
    Ingests curated database aggregate records from Question 3 and plots 
    the R-Squared size explanation percentage across distinct species classifications.
    """
    try:
        # 1. Ingest clean data schema generated by the database extraction engine
        df = pd.read_csv(csv_path)
        
        # Sort values to ensure a clean descending visual cascade
        df = df.sort_values(by="species_size_explanation_percentage", ascending=False).head(20)
        
        # 2. Establish a minimalist, high-contrast scientific layout grid
        sns.set_theme(style="whitegrid")
        plt.figure(figsize=(12, 8))
        
        # 3. Generate a horizontal bar plot showing the size explanation percentage per species
        ax = sns.barplot(
            data=df, 
            x="species_size_explanation_percentage", 
            y="tree_species", 
            palette="viridis",
            hue="tree_species",
            legend=False
        )
        
        # 4. Annotate the bars with their exact percentage values for clear review
        for container in ax.containers:
            ax.bar_label(container, fmt='%.1f%%', padding=5, fontsize=9, color='black', fontweight='bold')
        
        # 5. Apply clean typography labels matching the analytical methodology of Question 3
        plt.title("Statistical Variance Mapping: How Much Tree Size (DBH) Accounts for Ecosystem Yield Variance", fontsize=12, pad=20, fontweight='bold')
        plt.xlabel("Coefficient of Determination (R² Value expressed as %)", fontsize=10, labelpad=10)
        plt.ylabel("Taxonomic Tree Species (Top 20 Sample Groups)", fontsize=10)
        plt.xlim(0, 115) # Leave room for text annotations
        
        # 6. Compile the high-resolution portfolio asset
        plt.tight_layout()
        plt.savefig(output_path, dpi=300)
        print(f"[SUCCESS] High-resolution Question 3 visualization compiled from SQL aggregate layers: {output_path}")
        
    except Exception as e:
        print(f"[ERROR] Pipeline visualization compilation failure: {str(e)}")

if __name__ == "__main__":
    generate_regression_plot()
