import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

def generate_regression_plot(csv_path="database_output.csv", output_path="species_size_vs_benefits_regression.png"):
    """
    Ingests curated database aggregate records and plots structural linear trends
    mapping physical average trunk scales against absolute environmental dollar yields.
    """
    try:
        # 1. Ingest clean data schema generated by the database extraction engine
        df = pd.read_csv(csv_path)
        
        # 2. Establish a minimalist, high-contrast scientific layout grid
        sns.set_theme(style="whitegrid")
        plt.figure(figsize=(10, 6))
        
        # 3. Plot multi-species variance cluster coordinates directly from database averages
        sns.regplot(
            data=df, 
            x="avg_dbh_inches", 
            y="avg_yearly_benefits_usd", 
            color="darkslateblue",
            scatter_kws={'alpha': 0.6, 's': 70}, 
            line_kws={'color': 'crimson', 'linewidth': 2.5}
        )
        
        # 4. Apply clean typography labels matching the analytical methodology
        plt.title("Variance Mapping: Average Tree Species Size vs. Ecosystem Yield", fontsize=12, pad=15, fontweight='bold')
        plt.xlabel("Average Diameter at Breast Height (DBH) in Inches", fontsize=10)
        plt.ylabel("Average Total Yearly Ecosystem Benefits ($ USD)", fontsize=10)
        
        # 5. Compile the high-resolution portfolio asset
        plt.tight_layout()
        plt.savefig(output_path, dpi=300)
        print(f"[SUCCESS] High-resolution visualization compiled from SQL aggregate layers: {output_path}")
        
    except Exception as e:
        print(f"[ERROR] Pipeline visualization compilation failure: {str(e)}")

if __name__ == "__main__":
    generate_regression_plot()
